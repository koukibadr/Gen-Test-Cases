// Builds the issue comment: a readable summary for people, and the full YAML
// in a collapsed block for machines. Kept under GitHub's 65,536-character limit.
import { MARKER } from "./github.mjs";
import { counts } from "./cases.mjs";

const LIMIT = 65_000;
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function caseDetails(c) {
  const lines = [`#### ${c.id}: ${c.title}`, ""];
  lines.push(`\`${c.type}\` · ${c.priority} · ${c.layer} · ${c.blocking ? "**blocking**" : "non-blocking"} · source: ${c.expected_source}` +
    (c.requires?.length ? ` · requires: ${c.requires.join(", ")}` : ""), "");
  if (c.preconditions?.length) lines.push("**Preconditions**", ...c.preconditions.map((p) => `- ${p}`), "");
  lines.push("**Steps**", ...c.steps.map((s, i) => `${i + 1}. ${s}`), "");
  if (c.data?.length) lines.push("**Data**", ...c.data.map((d) => `- \`${JSON.stringify(d)}\``), "");
  lines.push("**Expected**", ...c.expected.map((e) => `- ${e}`), "");
  return lines.join("\n");
}

export function renderComment({ doc, yamlText, result, model, runUrl, added, kept }) {
  const n = counts(doc.cases);
  const head = [
    MARKER,
    `### Test cases for #${doc.issue}`,
    "",
    `**${n.total} cases** (${n.happy} happy, ${n.negative} negative, ${n.edge} edge, ${n.regression} regression) · **${n.blocking} blocking** · result: \`${result}\`` +
      (kept ? ` · ${added} new, ${kept} kept from the previous run` : ""),
    doc.stack ? `Stack: ${doc.stack}` : "",
    "",
  ];

  const criteria = ["**Acceptance criteria**", ""];
  for (const a of doc.criteria) {
    const ids = doc.cases.filter((c) => c.criterion === a.id).map((c) => c.id);
    criteria.push(`- **${a.id}**${a.derived ? " (derived)" : ""}: ${a.text}${ids.length ? `  \n  ${ids.join(", ")}` : "  \n  _not covered_"}`);
  }
  criteria.push("");

  const table = ["| ID | Type | Priority | Blocking | Criterion | Title |", "|---|---|---|---|---|---|",
    ...doc.cases.map((c) => `| ${c.id} | ${c.type} | ${c.priority} | ${c.blocking ? "yes" : "no"} | ${c.criterion} | ${cell(c.title)} |`), ""];

  const problems = [];
  if (doc.uncovered.length) problems.push("**Not covered**", ...doc.uncovered.map((u) => `- ${u.criterion}: ${u.reason}`), "");
  if (doc.open_questions.length) problems.push("**Open questions**", ...doc.open_questions.map((q) => `- [ ] ${q}`), "");

  const details = ["<details><summary>Steps and expected results</summary>", "", ...doc.cases.map(caseDetails), "</details>", ""];
  const yaml = ["<details><summary>cases.yaml (machine-readable)</summary>", "", "```yaml", yamlText.trimEnd(), "```", "", "</details>", ""];
  const foot = [`<sub>Generated by gen-test-cases v0 with \`${model}\`${runUrl ? ` · [workflow run](${runUrl})` : ""}. Edits to this comment are kept in its history.</sub>`];

  const build = (...sections) => sections.flat().filter((l) => l !== null).join("\n");
  let body = build(head, criteria, table, problems, details, yaml, foot);
  if (body.length > LIMIT) {
    body = build(head, criteria, table, problems, ["_Steps omitted: the comment would exceed GitHub's size limit._", ""], yaml, foot);
  }
  if (body.length > LIMIT) {
    body = build(head, criteria, table, problems, ["_Steps and YAML omitted: too large for one comment. Download the cases file from the workflow run's artifacts._", ""], foot);
  }
  return body;
}
